// tests/checksum.test.js
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { internetChecksum } from '../packet/checksum.js';

test('Internet checksum — ví dụ IPv4 header kinh điển (Wikipedia) = 0xb861', () => {
  // Header IPv4 mẫu, trường checksum để 0:
  const header = [
    0x45, 0x00, 0x00, 0x73, 0x00, 0x00, 0x40, 0x00,
    0x40, 0x11, 0x00, 0x00, 0xc0, 0xa8, 0x00, 0x01,
    0xc0, 0xa8, 0x00, 0xc7,
  ];
  assert.equal(internetChecksum(header), 0xb861);
});

test('Checksum của block ĐÃ chứa checksum đúng thì = 0', () => {
  const header = [
    0x45, 0x00, 0x00, 0x73, 0x00, 0x00, 0x40, 0x00,
    0x40, 0x11, 0xb8, 0x61, 0xc0, 0xa8, 0x00, 0x01,
    0xc0, 0xa8, 0x00, 0xc7,
  ];
  assert.equal(internetChecksum(header), 0x0000);
});

test('Số byte lẻ: byte cuối nằm ở byte cao', () => {
  // [0x00, 0x01, 0xf2] -> 0x0001 + 0xf200 = 0xf201 -> ~ = 0x0dfe
  assert.equal(internetChecksum([0x00, 0x01, 0xf2]), 0x0dfe);
});
